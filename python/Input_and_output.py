# 🧾 Python Input & Output (Short Notes)

# 🟩 print() → Output Function

# Used to display output on screen.
# Syntax: print(value1, value2, ..., sep=' ', end='\n')

# Parameters:
# sep → Separator (default space)
# end → What to print at end (default newline)


# Examples:
# print("Hello, Python!")          # Hello, Python!
# print("My age is", 20)           # My age is 20
# print("A", "B", sep="-")         # A-B
# print("Hello", end=" "); print("World")  # Hello World

# 🟦 input() → Input Function

# Used to take user input (always as string).

# Syntax: variable = input("Prompt message: ")

# Example:

# name = input("Enter your name: ")
# print("Hello,", name)

