# arithmetic_operators.py
# -----------------------
# 🎯 In this file, we’ll learn about Arithmetic Operators in Python.

# Arithmetic operators are used to perform basic mathematical operations.
# Python supports all common arithmetic operators like +, -, *, /, etc.


# ----------------------------------------------------------
# 🧮 List of Arithmetic Operators
# ----------------------------------------------------------
# Operator | Description              | Example
# -------- | ------------------------ | ----------------
# +        | Addition                 | 10 + 5 = 15
# -        | Subtraction              | 10 - 5 = 5
# *        | Multiplication           | 10 * 5 = 50
# /        | Division (float result)  | 10 / 5 = 2.0
# %        | Modulus (remainder)      | 10 % 3 = 1
# **       | Exponentiation (power)   | 2 ** 3 = 8
# //       | Floor Division           | 10 // 3 = 3 (integer result)

# ----------------------------------------------------------
# 🔹 Examples
# ----------------------------------------------------------

a = 10
b = 3

print("🔹 a =", a)
print("🔹 b =", b)
print("------------------------------")

# Addition
print("Addition (a + b):", a + b)

# Subtraction
print("Subtraction (a - b):", a - b)

# Multiplication
print("Multiplication (a * b):", a * b)

# Division
print("Division (a / b):", a / b)

# Modulus
print("Modulus (a % b):", a % b)

# Exponentiation
print("Exponentiation (a ** b):", a ** b)

# Floor Division
print("Floor Division (a // b):", a // b)

# ----------------------------------------------------------
# 💡 Note:
# / → always gives float (even if both numbers are integers)
# // → gives integer result by removing decimal part
# ----------------------------------------------------------


# ----------------------------------------------------------
# 🎯 Example Use Case
# ----------------------------------------------------------

x = 15
y = 4

result = (x + y) * 2 / 5
print("\n🔸 Combined Expression ((x + y) * 2 / 5):", result)

# ----------------------------------------------------------
# ✅ Summary:
# +  → Add
# -  → Subtract
# *  → Multiply
# /  → Divide (float)
# %  → Remainder
# ** → Power
# // → Integer division
# ----------------------------------------------------------
