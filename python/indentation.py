# 🔹 What is Indentation?

# Indentation means adding spaces or tabs at the beginning of a line of code.
# It shows which statements belong together — in other words, it defines code blocks.

# Unlike other languages (like C++, Java, or JavaScript),
# ➡️ Python uses indentation instead of braces {} to indicate blocks of code.

# Example 

