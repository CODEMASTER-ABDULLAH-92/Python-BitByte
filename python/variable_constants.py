


# A **variable** is a **named location** in memory that stores data (a value).
# You can **change** the value of a variable anytime during program execution.

# ---

# ### 🔹 **Syntax:**

# ```python
# variable_name = value
# ```

# ### 🔹 **Examples:**

# ```python
# name = "Abdullah"
# age = 20
# height = 5.9
# is_student = True
# ```

# Here,

# * `name`, `age`, `height`, and `is_student` are **variables**.
# * Their **values** can be changed later.

# ---

# ### 🔹 **Reassigning Variables:**

# ```python
# age = 20
# age = 21   # value changed
# print(age)  # Output: 21
# ```

# Python allows you to **change (mutate)** variable values freely.

# ---

# ### 🔹 **Rules for Variable Names:**

# 1. Must start with a **letter** or **underscore (_)**.
# 2. Can include **letters, digits, and underscores**.
# 3. Cannot start with a **digit**.
# 4. Cannot use **keywords** (like `if`, `class`, `return`, etc.).
# 5. Python is **case-sensitive** → `Age` ≠ `age`.

# ---

# ## 🟦 **Constants in Python**

# ### 🔹 **Definition:**

# A **constant** is a variable whose value is **not supposed to change** during program execution.
# 👉 Python doesn’t have *built-in constant support*,
# but **by convention**, we use **uppercase letters** to represent constants.

# ---

# ### 🔹 **Example:**

# ```python
# PI = 3.14159
# GRAVITY = 9.8
# MAX_USERS = 100
# ```

# These are treated as constants — you **should not** change their values later.

