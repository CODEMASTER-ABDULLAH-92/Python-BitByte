# 🔹 1. Integer (int)

# Used to represent whole numbers (positive, negative, or zero).

# No decimal point.

# Python integers have unlimited precision (can store very large numbers).


a = 10
b = -25
c = 0
print(type(a))   # <class 'int'>

# -----------------------------------------\

# 🔹 2. Floating-point (float)

# -------------------------------------------\

# Represents real numbers with decimal points.

# Stored using 64-bit double precision (IEEE 754 standard).

# Can also represent numbers in scientific notation.

x = 3.14
y = -2.5
z = 2.5e3   # 2.5 × 10³ = 2500.0
print(type(x))   # <class 'float'>


