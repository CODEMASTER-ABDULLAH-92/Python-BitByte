
# ### 🟩 **Keywords**

# **Definition:**
# Keywords are **reserved words** in Python that have **special meanings** and are **used by the language syntax itself**.
# You **cannot use** them as variable names, function names, or identifiers.

# **Examples of keywords:**

# ```
# False, True, None, and, or, not,
# if, else, elif, while, for, break, continue, return,
# import, from, class, def, try, except, finally, with,
# as, is, in, global, nonlocal, lambda, yield, pass, del, raise
# ```

# 👉 To see all Python keywords in your system:

# ```python
# import keyword
# print(keyword.kwlist)
# ```

# **Example:**

# ```python
# if = 10   # ❌ Invalid: 'if' is a keyword
# ```

# ---

# ### 🟦 **Identifiers**

# **Definition:**
# Identifiers are **names** used to identify variables, functions, classes, objects, or other entities in Python.

# **Examples of identifiers:**

# ```python
# name = "Abdullah"
# age = 20
# def greet(): ...
# class Car: ...
# ```

# ---

# ### ✅ **Rules for Identifiers:**

# 1. Can contain **letters (A–Z, a–z)**, **digits (0–9)**, and **underscores (_)**.
# 2. **Cannot start** with a digit.
# 3. **Cannot** be a Python **keyword**.
# 4. Are **case-sensitive** (`Name`, `name`, and `NAME` are all different).
# 5. No special symbols allowed (`@`, `$`, `%`, etc. are invalid).

